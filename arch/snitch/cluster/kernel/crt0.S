// Snitch cluster startup. All the cluster cores are released by the bootrom
// and jump here. With the multicore option (CONFIG_SNITCH_MULTICORE), all of
// them run main(), like with snRuntime: the compute cores and the data-mover
// core, which main() tells apart with snrt_cluster_core_idx()
// (pmsis/chips/snitch/snrt.h). Without it, only core 0 does and the others
// are parked.
//
// Each core takes its stack at the end of the TCDM, where snRuntime puts it
// (core N in the Nth slot below `stack`). Only core 0 goes through the OS
// initialization (BSS, libc, constructors); the others wait on the cluster
// hardware barrier, which core 0 joins at the end of its init (__pi_init_soc in
// hal.c), so no core enters main before the runtime is up.

    .global _start
    .type   _start, @function
_start:
    // FP state on (mstatus.FS = initial)
    li    t0, (1 << 13)
    csrs  mstatus, t0

    csrr  t0, mhartid

    la    x2, stack
    slli  t2, t0, CONFIG_STACK_SIZE_LOG2
    sub   x2, x2, t2

#ifdef CONFIG_SNITCH_MULTICORE
    bnez  t0, __pi_hart_secondary
#else
    bnez  t0, __pi_hart_park
#endif

    // Work-around to cancel call-stack generated by rom on some architectures
    // to not show it in profiler
    la    t0, _start_call_stack_reset_0
    jr    t0
_start_call_stack_reset_0:

    // Do all other initializations from C code, then main() and exit
    la    t0, __pi_init_start
    addi  a0, x0, 0
    jalr  x1, t0

#ifdef CONFIG_SNITCH_MULTICORE
__pi_hart_secondary:
    // Rendezvous with core 0 once the runtime is initialized
    csrr  x0, 0x7C2

    la    t0, main
    jalr  x1, t0

    // Nothing to report: core 0 owns the exit status.
#endif
__pi_hart_park:
    wfi
    j     __pi_hart_park
